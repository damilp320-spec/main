// Студия плагинов Minecraft: генерация проектов Paper/Spigot и компиляция.
const fs = require('fs');
const path = require('path');
const { spawn, exec } = require('child_process');

const system = require('./system');

function mcRoot() {
  const root = path.join(system.safeRoot(), 'minecraft-plugins');
  fs.mkdirSync(root, { recursive: true });
  return root;
}

function checkEnv() {
  const check = (cmd) => new Promise((res) => exec(cmd, (err, stdout, stderr) => res(err ? null : (stdout || stderr).split('\n')[0].trim())));
  return Promise.all([check('java -version 2>&1'), check('mvn -v'), check('gradle -v')]).then(([java, mvn, gradle]) => ({
    java: !!java, javaVersion: java || null,
    maven: !!mvn, mavenVersion: mvn || null,
    gradle: !!gradle, gradleVersion: gradle || null,
    hints: {
      java: 'winget install Microsoft.OpenJDK.21',
      maven: 'winget install Apache.Maven',
      gradle: 'winget install Gradle.Gradle'
    }
  }));
}

function listProjects() {
  const root = mcRoot();
  return fs.readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => {
      const dir = path.join(root, d.name);
      const jar = findJar(dir);
      const kind = projectKind(dir);
      return { name: d.name, dir, jar, kind, hasPom: fs.existsSync(path.join(dir, 'pom.xml')), buildable: fs.existsSync(path.join(dir, 'pom.xml')) || fs.existsSync(path.join(dir, 'build.gradle')) };
    });
}

function findJar(dir) {
  // Maven кладёт jar в target/, Gradle — в build/libs/.
  for (const sub of ['target', 'build/libs']) {
    const d = path.join(dir, sub);
    if (!fs.existsSync(d)) continue;
    const jars = fs.readdirSync(d).filter((f) => f.endsWith('.jar') && !f.includes('original') && !f.includes('-sources') && !f.includes('-dev'));
    if (jars.length) return path.join(d, jars[0]);
  }
  return null;
}

function projectKind(dir) {
  if (fs.existsSync(path.join(dir, 'pom.xml'))) return 'plugin';
  if (fs.existsSync(path.join(dir, 'src/main/resources/fabric.mod.json'))) return 'fabric';
  if (fs.existsSync(path.join(dir, 'build.gradle'))) return 'forge';
  return 'plugin';
}

