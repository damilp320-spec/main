const toolSchemas = [
  { type: 'function', function: { name: 'mc_create_plugin', description: 'Создать новый проект плагина Minecraft (Paper/Spigot) из шаблона. Шаблоны: basic, command, listener.', parameters: { type: 'object', properties: { name: { type: 'string' }, template: { type: 'string' }, mcVersion: { type: 'string' } }, required: ['name'] } } },
  { type: 'function', function: { name: 'mc_compile_plugin', description: 'Скомпилировать проект плагина Minecraft в .jar через Maven. Возвращает путь к jar или лог ошибок.', parameters: { type: 'object', properties: { name: { type: 'string' } }, required: ['name'] } } },
  { type: 'function', function: { name: 'mc_list_plugins', description: 'Показать список проектов плагинов Minecraft.', parameters: { type: 'object', properties: {} } } }
];

const toolHandlers = {
  async mc_create_plugin(args) {
    const r = createProject(args);
    return r.ok ? `Проект создан: ${r.dir}\nГлавный класс: ${r.mainClass}\nИсходники можно править через write_file.` : 'Ошибка: ' + r.error;
  },
  async mc_compile_plugin({ name }) {
    const r = await compileProject(name, null);
    return r.ok ? 'Готово! JAR: ' + r.jar : 'Ошибка сборки: ' + r.error + '\n' + String(r.log || '').slice(-1500);
  },
  async mc_list_plugins() {
    const list = listProjects();
    return list.length ? list.map((p) => `${p.name}${p.jar ? ' [собран: ' + p.jar + ']' : ''}`).join('\n') : 'Проектов нет.';
  }
};

module.exports = { mcRoot, checkEnv, listProjects, createProject, compileProject, deleteProject, TEMPLATES, toolSchemas, toolHandlers };
