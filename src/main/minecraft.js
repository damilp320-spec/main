// Создание скелета мода Forge/Fabric (Gradle-проект).
function createMod({ name, loader = 'fabric', mcVersion = '1.21.1', author = 'MytheraAI' }) {
  const safe = name.replace(/[^a-zA-Z0-9_-]/g, '').slice(0, 40) || 'MyMod';
  const id = safe.toLowerCase();
  const cls = javaClassName(safe);
  const pkg = 'com.mythera.' + id;
  const dir = path.join(mcRoot(), safe);
  if (fs.existsSync(dir)) return { ok: false, error: 'Проект с таким именем уже существует' };
  const javaDir = path.join(dir, 'src/main/java', ...pkg.split('.'));
  const resDir = path.join(dir, 'src/main/resources');
  fs.mkdirSync(javaDir, { recursive: true });
  fs.mkdirSync(resDir, { recursive: true });

  if (loader === 'fabric') {
    fs.writeFileSync(path.join(dir, 'build.gradle'), `plugins { id 'fabric-loom' version '1.7-SNAPSHOT'; id 'java' }
version = '1.0.0'
group = '${pkg}'
base { archivesName = '${id}' }
repositories { mavenCentral() }
dependencies {
  minecraft "com.mojang:minecraft:${mcVersion}"
  mappings "net.fabricmc:yarn:${mcVersion}+build.1:v2"
  modImplementation "net.fabricmc:fabric-loader:0.16.0"
}
java { sourceCompatibility = JavaVersion.VERSION_21; targetCompatibility = JavaVersion.VERSION_21 }
`);
    fs.writeFileSync(path.join(dir, 'settings.gradle'), `pluginManagement { repositories { maven { url 'https://maven.fabricmc.net/' }; gradlePluginPortal() } }\nrootProject.name = '${id}'\n`);
    fs.writeFileSync(path.join(dir, 'gradle.properties'), `org.gradle.jvmargs=-Xmx2G\n`);
    fs.writeFileSync(path.join(resDir, 'fabric.mod.json'), JSON.stringify({
      schemaVersion: 1, id, version: '1.0.0', name: safe, description: 'Mod by Mythera AI Hub', authors: [author],
      environment: '*', entrypoints: { main: [`${pkg}.${cls}`] }, depends: { fabricloader: '>=0.16.0', minecraft: `~${mcVersion}` }
    }, null, 2));
    fs.writeFileSync(path.join(javaDir, cls + '.java'), `package ${pkg};

import net.fabricmc.api.ModInitializer;

public class ${cls} implements ModInitializer {
    @Override
    public void onInitialize() {
        System.out.println("[${safe}] Fabric mod initialized!");
    }
}
`);
  } else {
    // Forge
    fs.writeFileSync(path.join(dir, 'build.gradle'), `plugins { id 'net.minecraftforge.gradle' version '6.0.+'; id 'java' }
version = '1.0.0'
group = '${pkg}'
java { toolchain { languageVersion = JavaLanguageVersion.of(21) } }
minecraft { mappings channel: 'official', version: '${mcVersion}' }
repositories { mavenCentral() }
dependencies { minecraft 'net.minecraftforge:forge:${mcVersion}-latest' }
jar { manifest { attributes(['Specification-Title': '${id}']) } }
`);
    fs.writeFileSync(path.join(dir, 'settings.gradle'), `pluginManagement { repositories { gradlePluginPortal(); maven { url = 'https://maven.minecraftforge.net/' } } }\nrootProject.name = '${id}'\n`);
    fs.writeFileSync(path.join(dir, 'gradle.properties'), `org.gradle.jvmargs=-Xmx3G\n`);
    const metaDir = path.join(resDir, 'META-INF'); fs.mkdirSync(metaDir, { recursive: true });
    fs.writeFileSync(path.join(metaDir, 'mods.toml'), `modLoader="javafml"\nloaderVersion="[47,)"\nlicense="MIT"\n[[mods]]\nmodId="${id}"\nversion="1.0.0"\ndisplayName="${safe}"\nauthors="${author}"\ndescription="Mod by Mythera AI Hub"\n`);
    fs.writeFileSync(path.join(javaDir, cls + '.java'), `package ${pkg};

import net.minecraftforge.fml.common.Mod;

@Mod("${id}")
public class ${cls} {
    public ${cls}() {
        System.out.println("[${safe}] Forge mod loaded!");
    }
}
`);
  }
  return { ok: true, name: safe, dir, loader, mainClass: `${pkg}.${cls}` };
}

// Компиляция мода через Gradle.
function compileMod(name, onLog) {
  return new Promise(async (resolve) => {
    const dir = path.join(mcRoot(), name);
    if (!fs.existsSync(path.join(dir, 'build.gradle'))) return resolve({ ok: false, error: 'build.gradle не найден' });
    const env = await checkEnv();
    if (!env.java) return resolve({ ok: false, error: 'Java (JDK 21) не установлена. Выполните: ' + env.hints.java });
    const wrapper = process.platform === 'win32' ? 'gradlew.bat' : './gradlew';
    const useWrapper = fs.existsSync(path.join(dir, process.platform === 'win32' ? 'gradlew.bat' : 'gradlew'));
    if (!useWrapper && !env.gradle) return resolve({ ok: false, error: 'Gradle не установлен. Выполните: ' + env.hints.gradle });
    const cmd = useWrapper ? wrapper : (process.platform === 'win32' ? 'gradle.bat' : 'gradle');
    const proc = spawn(cmd, ['build', '--no-daemon'], { cwd: dir, shell: process.platform === 'win32' });
    let log = '';
    const push = (d) => { log += d; onLog && onLog(String(d)); };
    proc.stdout.on('data', push); proc.stderr.on('data', push);
    const timer = setTimeout(() => { proc.kill(); resolve({ ok: false, error: 'Таймаут сборки (15 мин)', log }); }, 900000);
    proc.on('close', (code) => {
      clearTimeout(timer);
      const jar = findJar(dir);
      resolve(code === 0 && jar ? { ok: true, jar, log } : { ok: false, error: 'Сборка завершилась с ошибкой (код ' + code + '). Модам нужен интернет для скачивания зависимостей при первой сборке.', log });
    });
    proc.on('error', (e) => { clearTimeout(timer); resolve({ ok: false, error: e.message, log }); });
  });
}

